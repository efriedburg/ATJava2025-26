// Java-provided constant static value: Math.PI
// Java-provided static method: Math.sqrt()
// Example program can be seen below:

public class HW26PartA {
    public static void main(String[] args) {
        
        // Finding the area of a circle with a radius of 5.0 using Math.PI
        double radius = 5.0;
        double area = Math.PI * Math.pow(radius, 2);
        System.out.println("The area of the circle is: " + area);

        // Finding the square root of 16 using Math.sqrt()
        double number = 16.0;
        double squareRoot = Math.sqrt(number);
        System.out.println("The square root of 16 is: " + squareRoot);
    }


}
